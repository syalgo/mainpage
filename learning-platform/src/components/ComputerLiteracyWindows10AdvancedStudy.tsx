          <h3><span>04</span> [설정] → [접근성]</h3>
          <ul>
            <li>신체에 장애가 있거나 컴퓨터에 익숙하지 않은 사람들이 컴퓨터를 편리하고 쉽게 사용할 수 있도록 키보드, 소리, 마우스 등의 설정을 변경함</li>
